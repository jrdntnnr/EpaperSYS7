#!/usr/bin/env python3
"""Extract a bitmap font (NFNT/FONT) from a Macintosh System file.

Input is the System file in MacBinary form, e.g.
  hmount system.hfv 1 && hcopy -m ':System Folder:System' System.bin
Output is a C header describing the strike for firmware/papers3_mac/main/mac_font.h.

usage: mac_font.py System.bin "Chicago" 12 out.h
"""
import struct
import sys

MACBINARY_HEADER = 128
FOND_ASSOC_TABLE = 52
MISSING_GLYPH = 0xFFFF


def resources(macbinary):
    """Map (type, id) -> (name, data) for every resource in the file."""
    data_len, rsrc_len = struct.unpack(">II", macbinary[83:91])
    rsrc_off = MACBINARY_HEADER + ((data_len + 127) // 128) * 128
    fork = macbinary[rsrc_off:rsrc_off + rsrc_len]
    data_off, map_off = struct.unpack(">II", fork[:8])
    rmap = fork[map_off:]
    type_off, name_off = struct.unpack(">HH", rmap[24:28])
    types = rmap[type_off:]
    out = {}
    count = struct.unpack(">H", types[:2])[0] + 1
    for i in range(count):
        rtype, n, off = struct.unpack(">4sHH", types[2 + 8 * i:10 + 8 * i])
        for j in range(n + 1):
            entry = types[off + 12 * j:off + 12 * j + 12]
            rid, noff, attr_off = struct.unpack(">hHI", entry[:8])
            doff = data_off + (attr_off & 0xFFFFFF)
            name = None
            if noff != 0xFFFF:
                ln = rmap[name_off + noff]
                name = rmap[name_off + noff + 1:name_off + noff + 1 + ln].decode("mac_roman")
            ln = struct.unpack(">I", fork[doff:doff + 4])[0]
            out[(rtype.decode("latin1"), rid)] = (name, fork[doff + 4:doff + 4 + ln])
    return out


def strike_id(fond, size):
    """Font association table: plain-style strike of the given point size."""
    n = struct.unpack(">H", fond[FOND_ASSOC_TABLE:FOND_ASSOC_TABLE + 2])[0] + 1
    for i in range(n):
        psize, style, rid = struct.unpack(">HHH", fond[FOND_ASSOC_TABLE + 2 + 6 * i:FOND_ASSOC_TABLE + 8 + 6 * i])
        if psize == size and style == 0:
            return rid
    raise SystemExit(f"no plain {size}pt strike")


def parse_strike(nfnt):
    f = struct.unpack(">HHHHhhHHHHHHH", nfnt[:26])
    (_, first, last, wid_max, kern_max, _, rect_w, rect_h, ow_loc, ascent, descent, leading, row_words) = f
    bits_off = 26
    bits_len = row_words * 2 * rect_h
    loc_off = bits_off + bits_len
    nglyphs = last - first + 2  # includes the missing glyph
    loc = struct.unpack(f">{nglyphs + 1}H", nfnt[loc_off:loc_off + 2 * (nglyphs + 1)])
    ow_off = 16 + ow_loc * 2  # offset is in words from the owTLoc field
    ow = struct.unpack(f">{nglyphs}H", nfnt[ow_off:ow_off + 2 * nglyphs])
    return dict(first=first, last=last, wid_max=wid_max, kern_max=kern_max, height=rect_h,
                ascent=ascent, descent=descent, leading=leading, row_bytes=row_words * 2,
                bits=nfnt[bits_off:loc_off], loc=loc, ow=ow)


def emit(s, name, out):
    ident = name.lower().replace(" ", "_")
    w = out.write
    w(f"/* Generated by tools/mac_font.py from the System file: {name}. */\n")
    w("#pragma once\n#include \"mac_font.h\"\n\n")
    w(f"static const uint8_t {ident}_bits[] = {{\n")
    for i in range(0, len(s["bits"]), 16):
        w("    " + ", ".join(f"0x{b:02x}" for b in s["bits"][i:i + 16]) + ",\n")
    w("};\n")
    w(f"static const uint16_t {ident}_loc[] = {{\n")
    for i in range(0, len(s["loc"]), 16):
        w("    " + ", ".join(str(v) for v in s["loc"][i:i + 16]) + ",\n")
    w("};\n")
    w(f"static const uint16_t {ident}_ow[] = {{\n")
    for i in range(0, len(s["ow"]), 16):
        w("    " + ", ".join(f"0x{v:04x}" for v in s["ow"][i:i + 16]) + ",\n")
    w("};\n")
    w(f"static const mac_font_t {ident} = {{\n")
    w(f"    .first = {s['first']}, .last = {s['last']}, .height = {s['height']},\n")
    w(f"    .ascent = {s['ascent']}, .descent = {s['descent']}, .leading = {s['leading']},\n")
    w(f"    .kern_max = {s['kern_max']}, .row_bytes = {s['row_bytes']},\n")
    w(f"    .bits = {ident}_bits, .loc = {ident}_loc, .ow = {ident}_ow,\n")
    w("};\n")


def main():
    path, name, size, out_path = sys.argv[1:5]
    res = resources(open(path, "rb").read())
    fond = next(d for (t, _), (n, d) in res.items() if t == "FOND" and n == name)
    rid = strike_id(fond, int(size))
    nfnt = res.get(("NFNT", rid)) or res.get(("FONT", rid))
    strike = parse_strike(nfnt[1])
    with open(out_path, "w") as out:
        emit(strike, f"{name} {size}", out)
    print(f"{name} {size}: NFNT {rid}, chars {strike['first']}..{strike['last']}, "
          f"{strike['height']} rows, {strike['row_bytes']} bytes/row")


if __name__ == "__main__":
    main()
